// Function to get holidays for a specific date
function getHolidaysForDate(dateStr, countries = ['US', 'UK', 'India']) {
  const holidays = [];
  const [year] = dateStr.split('-');
  const yearNum = parseInt(year);

  if (HOLIDAYS[yearNum]) {
    countries.forEach(country => {
      const countryHolidays = HOLIDAYS[yearNum][country] || [];
      const holiday = countryHolidays.find(h => h.date === dateStr);
      if (holiday) {
        holidays.push({
          name: holiday.name,
          country: country,
          type: 'holiday'
        });
      }
    });
  }

  return holidays;
}

// Function to get all holidays for a month
function getMonthHolidays(year, month, countries = ['US', 'UK', 'India']) {
  const holidays = [];
  const monthStr = String(month).padStart(2, '0');

  if (HOLIDAYS[year]) {
    countries.forEach(country => {
      const countryHolidays = HOLIDAYS[year][country] || [];
      const monthHolidays = countryHolidays.filter(h => h.date.startsWith(`${year}-${monthStr}`));
      holidays.push(...monthHolidays.map(h => ({
        ...h,
        country: country,
        type: 'holiday'
      })));
    });
  }

  return holidays;
}
